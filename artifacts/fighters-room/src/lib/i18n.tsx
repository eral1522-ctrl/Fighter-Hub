export type TranslationShape = typeof T.en;

const LanguageContext = createContext<{
  lang: Lang;
  t: TranslationShape;
  setLang: (l: Lang) => void;
}>({ lang: "en", t: T.en, setLang: () => {} });

const LANG_STORAGE_KEY = "ifa-lang";

function getInitialLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (stored === "en" || stored === "es") return stored;
  } catch {
    // localStorage unavailable (private mode, etc.) — fall through
  }
  return "en";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Initialize synchronously from localStorage so the very first render is
  // already in the saved language — no English flash before Spanish.
  const [lang, setLangState] = useState<Lang>(getInitialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_STORAGE_KEY, l);
    } catch {
      // Persisting is best-effort; the in-session language still switches.
    }
  }, []);
  const t = T[lang] as TranslationShape;
  return (
    <LanguageContext.Provider value={{ lang, t, setLang }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

export function LangSwitcher() {
  const { lang, setLang } = useLanguage();
  return (
    <div className="flex items-center gap-1 text-xs font-heading uppercase tracking-widest">
      <button
        onClick={() => setLang("en")}
        className={lang === "en" ? "text-primary font-bold" : "text-muted-foreground hover:text-white transition-colors"}
      >
        EN
      </button>
      <span className="text-muted-foreground">|</span>
      <button
        onClick={() => setLang("es")}
        className={lang === "es" ? "text-primary font-bold" : "text-muted-foreground hover:text-white transition-colors"}
      >
        ES
      </button>
    </div>
  );
}
